def sub(path, pairs):
    s = open(path, encoding="utf-8").read()
    for a, b in pairs:
        if a not in s: print("MISSING in", path, ":", a[:80])
        s = s.replace(a, b)
    open(path, "w", encoding="utf-8").write(s)

