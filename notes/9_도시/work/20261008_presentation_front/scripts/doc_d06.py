def make(key, pno, pr, name, ID, clip, dpi, desc, sentence, phrases, grade, note="", hl_pad=1.5, occ=None):
    """clip을 dpi로 잘라 name.png 저장, phrases(문장 일부)에 형광펜을 얹은 name_hl.png 저장."""
    path = P[key]
    import math
    width_pt = clip[2] - clip[0]
    dpi = int(min(600, max(dpi, math.ceil(1800 * 72 / width_pt))))  # 폭 1800px 이상이 되도록 (글자는 벡터라 해상도 손실 없음)
    img = D.render(path, pno, dpi=dpi, clip=clip)
    base = name + ".png"
    D.save(img, base)
    cap = CAP[key].format(pr=pr)
    bb = D.bbox_str(clip)
    meth = f"쪽 렌더(벡터 글자) {dpi}dpi 크롭"
    D.record(base, ID, desc, cap, path, f"{pno}/{pr}", img.size, grade, sentence, bb, meth, note)
    rects = []
    miss = []
    for ph in phrases:
        if isinstance(ph, tuple):  # (문구, 'all' 또는 n번째)
            txt, o = ph
        else:
            txt, o = ph, (occ or {}).get(ph, 1)
        if o == "all":  # 크롭 안에 있는 모든 일치를 칠한다
            rs = []
            k = 1
            while True:
                r = D.phrase_rects(path, pno, txt, k)
                if not r:
                    break
                rs += [x for x in r if x.y1 > clip[1] and x.y0 < clip[3] and x.x1 > clip[0] and x.x0 < clip[2]]
                k += 1
        else:
            rs = D.phrase_rects(path, pno, txt, o)
        if not rs:
            miss.append(txt)
        rects += rs
    if miss:
        print("  !! phrase 못 찾음:", miss)
    if rects:
        himg = D.highlight(img, rects, clip, dpi, pad=hl_pad)
        hname = name + "_hl.png"
        D.save(himg, hname)
        D.record(hname, ID, desc + " (형광펜 변형)", cap, path, f"{pno}/{pr}", himg.size, grade, sentence, bb,
                 meth + " + 형광펜(#FFE86B 55%)", note)
    print(f"{base}: {img.size}  hl={len(rects)}rects")
    return img


