def _check():
    ids = {n[0] for n in NODES}
    assert len(ids) == len(NODES), "중복 노드 id"
    bad = [(e[0], e[1]) for e in EDGES if e[0] not in ids or e[1] not in ids]
    if bad:
        print("알 수 없는 노드:", bad); sys.exit(1)
    from collections import Counter
    dup = [k for k, v in Counter((e[0], e[1], e[2]) for e in EDGES).items() if v > 1]
    if dup:
        print("중복 엣지:", dup); sys.exit(1)
    selfloop = [e[0] for e in EDGES if e[0] == e[1]]
    if selfloop:
        print("자기 순환:", selfloop); sys.exit(1)
    unknown = [k for k in CUR_SRC if k not in ids]
    if unknown:
        print("CUR_SRC 알 수 없는 노드:", unknown); sys.exit(1)

