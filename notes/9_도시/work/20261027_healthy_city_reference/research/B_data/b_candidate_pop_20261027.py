def tot(tab, y, codes, idx):
    s, miss = 0, []
    for c in codes:
        v = tab[y].get(key(c, y))
        if v is None:
            miss.append(c)
            continue
        s += v[idx]
    return s, miss


def young(y, codes):
    s = 0
    for c in codes:
        v = AGE[y].get(key(c, y))
        if v:
            s += v[4] + v[5]  # 20–29, 30–39
    return s


def old70(y, codes):
    s = 0
    for c in codes:
        v = AGE[y].get(key(c, y))
        if v:
            s += v[9] + v[10] + v[11] + v[12]
    return s


def pct(a, b):
    return round((b / a - 1) * 100, 1) if a else ''


